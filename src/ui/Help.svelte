<ol class="steps">
  <li>
    <strong>Beri nama pojok.</strong> Pilih satu pojok tanah sebagai <b>A</b>, lalu beri nama pojok berikutnya
    <b>B, C, D, …</b> berurutan mengelilingi tanah (arah mana saja, asal berurutan).
  </li>
  <li>
    <strong>Atur jumlah sisi</strong> sesuai jumlah pojok tanah (3–10).
  </li>
  <li>
    <strong>Ukur setiap sisi</strong> dengan meteran: AB, BC, CD, … sampai sisi terakhir kembali ke A.
  </li>
  <li>
    <strong>Ukur diagonal dari pojok A</strong> ke setiap pojok yang tidak bersebelahan (AC, AD, …). Tanpa diagonal,
    luas tanah tidak bisa dipastikan karena bentuknya bisa "miring".
  </li>
  <li>
    <strong>Cek gambar.</strong> Bentuknya harus mirip tanah Anda. Ketuk sebuah kolom untuk menyorot garisnya di gambar.
    Bila ada pojok yang terbalik, pakai tombol <b>↺ balik</b>.
  </li>
  <li>
    <strong>Bagi bidang (opsional).</strong> Di tab <b>Bagi</b>, pilih sisi acuan (mis. sisi depan), arah garis, dan
    cara membagi: sama luas, proporsi, atau luas tertentu.
  </li>
  <li>
    <strong>Pasang patok.</strong> Kartu <b>Posisi patok</b> menyebut sisi dan jarak dari pojok terdekat, mis. "Sisi BC:
    4,25 m dari pojok B".
  </li>
  <li>
    <strong>Bagikan.</strong> Tombol bagikan mengirim link berisi ukuran (mis. lewat WhatsApp). Penerima melihat denah yang
    sama.
  </li>
</ol>

<div class="notice notice-info">
  <strong>Tanah bentuk L atau U?</strong> Jadikan pojok yang menjorok ke dalam sebagai pojok A. Semua diagonal akan
  berada di dalam tanah, sehingga lebih mudah diukur dan tombol balik tidak diperlukan.
</div>

